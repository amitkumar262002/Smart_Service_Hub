// Pincode to State/City mapping
export const PINCODE_RANGES = Object.entries(INDIA_STATES_CITIES).map(([state, data]) => ({
  state,
  cities: data.cities,
  min: data.pincodeRange.min,
  max: data.pincodeRange.max
}))

// Validate pincode and return state/city
export function validateAndGetLocation(pincode: string): { state?: string; city?: string; valid: boolean } {
  const pin = parseInt(pincode, 10)
  if (isNaN(pin) || pincode.length !== 6) {
    return { valid: false }
  }

  const location = PINCODE_RANGES.find(range => pin >= range.min && pin <= range.max)
  if (location) {
    return {
      state: location.state,
      city: location.cities[0], // Default to first city
      valid: true
    }
  }

  return { valid: false }
}

// Get all states
export function getAllStates(): string[] {
  return Object.keys(INDIA_STATES_CITIES).sort()
}

// Get cities for a state
export function getCitiesForState(state: string): string[] {
  return (INDIA_STATES_CITIES as Record<string, any>)[state]?.cities || []
}
